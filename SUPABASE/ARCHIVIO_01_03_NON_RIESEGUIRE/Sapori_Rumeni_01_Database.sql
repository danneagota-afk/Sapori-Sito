-- Catalogo pubblico: restituisce soltanto campi non riservati, mai scorte esatte o costi.
create or replace function public.sr_catalog()
returns table(id integer, ro text, it text, price numeric, cat text, unit text, image text, desc_it text, desc_ro text, allergens text, availability text)
language sql stable security definer set search_path = '' as $$
 select p.id,p.ro,p.it,p.price,p.cat,p.unit,p.image,p.desc_it,p.desc_ro,p.allergens,
 case when not coalesce((s.data->>'open')::boolean,false) or p.stock-coalesce(r.qty,0)<=0 then 'unavailable'
 when p.stock-coalesce(r.qty,0)<=p.low then 'low' else 'available' end
 from public.sr_products p cross join public.sr_settings s
 left join lateral (select sum(l.qty) qty from public.sr_order_lines l join public.sr_orders o on o.id=l.order_id where l.product_id=p.id and o.status in ('Da confermare','Confermata','In preparazione','Pronta')) r on true
 where p.active and s.id=1 order by p.id;
$$;
revoke all on function public.sr_catalog() from public, anon, authenticated;
grant execute on function public.sr_catalog() to anon, authenticated;
