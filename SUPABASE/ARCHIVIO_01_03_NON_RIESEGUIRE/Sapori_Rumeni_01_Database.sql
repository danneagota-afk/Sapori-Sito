begin;
create table if not exists public.sr_staff (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check(role in ('owner','manager','warehouse','prep')),
  active boolean not null default true
);
create table if not exists public.sr_products (
  id integer generated by default as identity primary key,
  ro text not null, it text not null,
  price numeric(12,2) not null check(price>=0),
  cat text not null, unit text not null check(unit in ('kg','buc')),
  stock numeric(12,3) not null default 0 check(stock>=0),
  active boolean not null default true, image text not null default '',
  low numeric(12,3) not null default 2 check(low>=0),
  desc_it text not null default '', desc_ro text not null default '',
  allergens text not null default '', cost numeric(12,2) not null default 0 check(cost>=0),
  updated_at timestamptz not null default now(),
  check(unit='kg' or stock=trunc(stock))
);
create table if not exists public.sr_settings (
  id integer primary key check(id=1),
  data jsonb not null check(jsonb_typeof(data)='object')
);
create table if not exists public.sr_orders (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null unique,
  created_at timestamptz not null default now(),
  status text not null default 'Da confermare' check(status in ('Da confermare','Confermata','In preparazione','Pronta','Spedita','Ritirata','Consegnata','Annullata')),
  method text not null check(method in ('pickup','scheduled')),
  pickup_at timestamptz,
  customer jsonb not null check(jsonb_typeof(customer)='object'),
  total numeric(12,2) not null check(total>=0),
  payment_method text check(payment_method in ('card','paypal','bank','store')),
  payment_status text not null default 'pending' check(payment_status in ('pending','partial','paid','refunded','failed')),
  check(method<>'pickup' or pickup_at is not null)
);
create table if not exists public.sr_order_lines (
  order_id uuid not null references public.sr_orders(id) on delete restrict,
  product_id integer not null references public.sr_products(id) on delete restrict,
  qty numeric(12,3) not null check(qty>0),
  unit_price numeric(12,2) not null check(unit_price>=0),
  name_it text not null, name_ro text not null,
  primary key(order_id,product_id)
);
create table if not exists public.sr_payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.sr_orders(id),
  amount numeric(12,2) not null check(amount>0),
  kind text not null check(kind in ('payment','refund')),
  provider_reference text unique, created_at timestamptz not null default now()
);
create table if not exists public.sr_audit (
  id bigint generated always as identity primary key,
  actor uuid references auth.users(id) on delete set null,
  action text not null, detail jsonb not null default '{}', created_at timestamptz not null default now()
);
create table if not exists public.sr_notifications (
  id uuid primary key default gen_random_uuid(),
  order_id uuid references public.sr_orders(id),
  channel text not null, recipient text not null, payload jsonb not null,
  status text not null default 'pending', created_at timestamptz not null default now()
);
create index if not exists sr_orders_pickup_idx on public.sr_orders(pickup_at,status);
create index if not exists sr_order_lines_product_idx on public.sr_order_lines(product_id);
